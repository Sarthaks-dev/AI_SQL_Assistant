def match_demo_query(question):
    """
    Check if a question matches or closely resembles one of our demo queries.
    Returns:
        dict or None: {"sql": ..., "explanation": ...}
    """
    q_norm = question.strip().lower().rstrip("?").rstrip(".")

    for key, data in DEMO_QUERIES.items():
        k_norm = key.strip().lower().rstrip("?").rstrip(".")
        if q_norm == k_norm:
            return data

    # Partial keyword matching
    if "top 5 customer" in q_norm:
        return DEMO_QUERIES["Show the top 5 customers by total purchase."]
    if "top 5 product" in q_norm or "top products" in q_norm:
        return DEMO_QUERIES["What are the top 5 products by sales?"]
    if "sales by city" in q_norm or "sales in city" in q_norm:
        return DEMO_QUERIES["Show total sales by city."]
    if "category" in q_norm and ("revenue" in q_norm or "sales" in q_norm):
        return DEMO_QUERIES["Which product category generated the most revenue?"]
    if "monthly sales" in q_norm:
        return DEMO_QUERIES["Show monthly sales for 2023."]
    if "from mumbai" in q_norm:
        return DEMO_QUERIES["List customers from Mumbai."]
    if "above 1000" in q_norm:
        return DEMO_QUERIES["Show products with price above 1000."]
    if "average order" in q_norm:
        return DEMO_QUERIES["Show average order amount."]
    if "highest total purchase" in q_norm:
        return DEMO_QUERIES["Show the customer with the highest total purchase."]
    if "delete" in q_norm:
        return DEMO_QUERIES["Delete all customers."]
    if "drop" in q_norm:
        return DEMO_QUERIES["Drop the orders table."]
    if "update" in q_norm:
        return DEMO_QUERIES["Update all product prices to 0."]

    return None
